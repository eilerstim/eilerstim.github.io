#!/usr/bin/env node
// Builds assets/js/zones.js: IANA time zone -> [lat, lon] of the zone's principal location, from the
// tz database (zone1970.tab plus the backward links). The page uses the visitor's time zone to place
// the sun without asking for their location.
// Run: node scripts/build-zones.mjs   (downloads the two files into scripts/.cache on first run)
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const cache = join(root, 'scripts/.cache');
mkdirSync(cache, { recursive: true });
const BASE = 'https://raw.githubusercontent.com/eggert/tz/main/';

async function fetchCached(name) {
  const file = join(cache, name);
  if (!existsSync(file)) {
    const res = await fetch(BASE + name);
    if (!res.ok) throw new Error(`${name}: ${res.status}`);
    writeFileSync(file, await res.text());
  }
  return readFileSync(file, 'utf8');
}

// ISO 6709 "+4722+00832" or "+472212+0083212" -> [47.37, 8.53]
function coords(s) {
  const m = /^([+-])(\d{2})(\d{2})(\d{2})?([+-])(\d{3})(\d{2})(\d{2})?$/.exec(s);
  if (!m) throw new Error(`bad coordinates ${s}`);
  const lat = (Number(m[2]) + Number(m[3]) / 60 + Number(m[4] || 0) / 3600) * (m[1] === '-' ? -1 : 1);
  const lon = (Number(m[6]) + Number(m[7]) / 60 + Number(m[8] || 0) / 3600) * (m[5] === '-' ? -1 : 1);
  return [Math.round(lat * 100) / 100, Math.round(lon * 100) / 100];
}

const zones = {};
for (const line of (await fetchCached('zone1970.tab')).split('\n')) {
  if (!line || line.startsWith('#')) continue;
  const [, coord, tz] = line.split('\t');
  zones[tz] = coords(coord);
}
let links = 0;
for (const line of (await fetchCached('backward')).split('\n')) {
  const m = /^Link\s+(\S+)\s+(\S+)/.exec(line);
  if (!m) continue;
  const [, target, name] = m;
  if (zones[target] && !zones[name]) { zones[name] = zones[target]; links++; }
}
const sorted = Object.keys(zones).sort();
const body = sorted.map((k) => `${JSON.stringify(k)}:[${zones[k][0]},${zones[k][1]}]`).join(',\n');
writeFileSync(join(root, 'assets/js/zones.js'),
  `// Generated by scripts/build-zones.mjs from the IANA tz database (public domain). Do not edit by hand.\n` +
  `// time zone -> [latitude, longitude] of the zone's principal location.\nexport default {\n${body}\n};\n`);
console.log(`${sorted.length} zones (${links} backward links) written to assets/js/zones.js`);
